"""Write two ready-to-use joined tables (convenience copies of the core records).

data/records/training_buildings.csv
    The buildings used to train and validate the models (usable image, building in the
    attribute table; the primary label is empty where the reviewers could not judge the image): all building attributes + image metadata + AI features + labels +
    out-of-fold and final predicted probability.

data/records/manhattan_buildings_with_amr_index.csv
    All constructed buildings in Manhattan: all building attributes + predicted probability,
    AMR index, interval and domain flags + the observed label where one exists.

Every column comes unchanged from one of the core records; data/dictionaries/joined_tables_dictionary.csv
says which one. Regenerated by `python run_all.py analysis`.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from amr_access import config  # noqa: E402
from amr_access.dictionary import BUILDINGS, LABELS, PREDICTIONS  # noqa: E402

TRAINING_CSV = config.RECORDS_DIR / "training_buildings.csv"
ALL_CSV = config.RECORDS_DIR / "manhattan_buildings_with_amr_index.csv"

LABEL_COLS = ["camera_lon", "camera_lat", "camera_target_distance_m", "heading_deg", "fov_deg", "pano_id",
              "image_capture_date", "duplicate_request_group", "qa_camera_far", "qa_capture_before_2020",
              "image_usable", "stairs_present", "gate_present", "ramp_present", "accessible_rule",
              "gate_ramp_source", "gate_present_ai", "ramp_present_ai", "accessible_rule_ai",
              "ai_amr_can_reach_door", "ai_model", "ai_response_id"]
PRED_COLS = ["p_accessible", "amr_index", "p_accessible_q05", "p_accessible_q95", "p_accessible_oof",
             "p_accessible_ai_only", "amr_index_ai_only", "p_accessible_ai_only_q05", "p_accessible_ai_only_q95",
             "p_accessible_ai_only_oof",
             "in_training_nta", "categories_seen", "numeric_in_range", "in_domain", "model_version"]


def main() -> None:
    ids = {"bin": str, "bbl": str, "zipcode": str, "landuse": str, "nta2020": str}
    b = pd.read_csv(config.BUILDINGS_CSV, dtype=ids)
    lab = pd.read_csv(config.LABELS_CSV, dtype=ids)
    pred = pd.read_csv(config.PREDICTIONS_CSV, dtype=ids)

    all_b = b.merge(pred[["bin"] + PRED_COLS], on="bin", how="left", validate="one_to_one")
    all_b = all_b.merge(lab[["bin", "image_usable", "stairs_present", "gate_present", "ramp_present",
                             "accessible_rule", "gate_ramp_source", "gate_present_ai", "ramp_present_ai",
                             "accessible_rule_ai", "ai_amr_can_reach_door"]], on="bin", how="left",
                        validate="one_to_one")
    all_b.to_csv(ALL_CSV, index=False, float_format="%.10g", lineterminator="\n")

    train = lab[lab["image_usable"] & lab["in_building_table"]][["bin"] + LABEL_COLS]
    train = b.merge(train, on="bin", how="inner", validate="one_to_one")
    train = train.merge(pred[["bin"] + PRED_COLS], on="bin", how="left", validate="one_to_one")
    train.to_csv(TRAINING_CSV, index=False, float_format="%.10g", lineterminator="\n")

    # column -> source record
    src = {**{c: "manhattan_buildings.csv" for c in BUILDINGS}, **{c: "streetview_entrance_labels.csv" for c in LABELS},
           **{c: "amr_accessibility_predictions.csv" for c in PREDICTIONS}}
    desc = {**{c: v[2] for c, v in BUILDINGS.items()}, **{c: v[2] for c, v in LABELS.items()},
            **{c: v[2] for c, v in PREDICTIONS.items()}}
    rows = []
    for name, df in [(TRAINING_CSV.name, train), (ALL_CSV.name, all_b)]:
        rows += [{"table": name, "column": c, "source_record": "all records (join key)" if c == "bin" else src[c],
                  "description": desc[c]} for c in df.columns]
    pd.DataFrame(rows).to_csv(config.DICTIONARY_DIR / "joined_tables_dictionary.csv", index=False,
                              lineterminator="\n")
    print(f"{TRAINING_CSV.name}: {train.shape[0]:,} x {train.shape[1]}  "
          f"(accessible: {train['accessible_rule'].mean():.1%})")
    print(f"{ALL_CSV.name}: {all_b.shape[0]:,} x {all_b.shape[1]}  "
          f"(with observed label: {all_b['accessible_rule'].notna().sum():,})")


if __name__ == "__main__":
    main()
